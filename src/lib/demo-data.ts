import type { Property, PropertyCategory, PropertyStatus, TransactionType } from "@/lib/types";

/**
 * Datos de demostración. Se usan SOLO cuando el proyecto no tiene
 * credenciales de Supabase (modo demo), para que puedas ver el diseño
 * y probar el buscador sin configuración. En producción se leen de la BD.
 */

const stock = (id: string) =>
  `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=1600&q=75`;

type DemoInput = {
  id: string;
  slug: string;
  title: string;
  description?: string;
  price: number;
  province: string;
  district: string;
  neighborhood?: string;
  transaction_type: TransactionType;
  property_type: PropertyCategory;
  bedrooms?: number | null;
  bathrooms?: number | null;
  parking_spots?: number | null;
  area_m2?: number | null;
  amenities?: string[];
  is_furnished?: boolean;
  images: string[];
  latitude?: number;
  longitude?: number;
  status?: PropertyStatus;
  is_featured?: boolean;
  daysAgo?: number;
};

function make(input: DemoInput): Property {
  const createdAt = new Date(Date.now() - (input.daysAgo ?? 1) * 86_400_000).toISOString();
  return {
    id: input.id,
    title: input.title,
    description: input.description ?? null,
    price: input.price,
    currency: "USD",
    province: input.province,
    district: input.district,
    neighborhood: input.neighborhood ?? null,
    transaction_type: input.transaction_type,
    property_type: input.property_type,
    bedrooms: input.bedrooms ?? null,
    bathrooms: input.bathrooms ?? null,
    parking_spots: input.parking_spots ?? null,
    area_m2: input.area_m2 ?? null,
    amenities: input.amenities ?? [],
    is_furnished: input.is_furnished ?? false,
    images: input.images,
    latitude: input.latitude ?? null,
    longitude: input.longitude ?? null,
    slug: input.slug,
    status: input.status ?? "published",
    is_featured: input.is_featured ?? false,
    seller_id: null,
    created_at: createdAt,
    updated_at: createdAt,
  };
}

